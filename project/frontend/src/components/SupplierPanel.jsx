import React, { useEffect, useState } from 'react';
import { api } from '../services/api';
import { CHART_COLORS as COLORS } from '../constants/colors';
import {
  BarChart, Bar, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer,
  RadarChart, Radar, PolarGrid, PolarAngleAxis, PolarRadiusAxis
} from 'recharts';

export default function SupplierPanel() {
  const [suppliers, setSuppliers] = useState([]);
  const [performance, setPerformance] = useState([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    Promise.allSettled([
      api.getSuppliers(),
      api.getSupplierPerformance()
    ]).then(([sup, perf]) => {
      if (sup.status === 'fulfilled') setSuppliers(sup.value);
      if (perf.status === 'fulfilled') setPerformance(perf.value);
      setLoading(false);
    });
  }, []);

  if (loading) return <div className="loading">Loading supplier data...</div>;

  const avgReliability = suppliers.length
    ? (suppliers.reduce((s, x) => s + (x.reliability_score || 0), 0) / suppliers.length * 100).toFixed(1)
    : 0;
  const totalProducts = suppliers.reduce((s, x) => s + (x.products_supplied || 0), 0);
  const avgLeadTime = suppliers.length
    ? (suppliers.reduce((s, x) => s + (x.lead_time_days || 0), 0) / suppliers.length).toFixed(1)
    : 0;

  // Chart data: products per supplier
  const supplierChart = performance.map(s => ({
    name: s.name.split(' ')[0],
    products: s.products_supplied,
    revenue: Math.round(s.total_revenue_generated),
    reliability: Math.round(s.reliability_score * 100),
  })).sort((a, b) => b.revenue - a.revenue);

  return (
    <div>
      <div className="page-header">
        <h2>🚚 Supplier Management</h2>
        <p>Supplier performance, reliability tracking, and product supply analysis</p>
      </div>

      <div className="kpi-grid">
        <div className="kpi-card blue">
          <div className="kpi-icon">🏭</div>
          <div className="kpi-label">Total Suppliers</div>
          <div className="kpi-value">{suppliers.length}</div>
        </div>
        <div className="kpi-card green">
          <div className="kpi-icon">✅</div>
          <div className="kpi-label">Avg Reliability</div>
          <div className="kpi-value">{avgReliability}%</div>
        </div>
        <div className="kpi-card purple">
          <div className="kpi-icon">📦</div>
          <div className="kpi-label">Products Supplied</div>
          <div className="kpi-value">{totalProducts}</div>
        </div>
        <div className="kpi-card orange">
          <div className="kpi-icon">🕐</div>
          <div className="kpi-label">Avg Lead Time</div>
          <div className="kpi-value">{avgLeadTime}d</div>
        </div>
      </div>

      <div className="grid-2">
        {/* Revenue by Supplier */}
        <div className="card">
          <div className="card-title">Revenue Generated by Supplier</div>
          <div className="chart-container">
            <ResponsiveContainer width="100%" height="100%">
              <BarChart data={supplierChart} layout="vertical">
                <CartesianGrid strokeDasharray="3 3" stroke="rgba(255,255,255,0.05)" />
                <XAxis type="number" tick={{ fill: '#9898b8', fontSize: 11 }} />
                <YAxis type="category" dataKey="name" tick={{ fill: '#9898b8', fontSize: 11 }} width={120}
                  tickFormatter={(v) => v.length > 16 ? v.slice(0, 14) + '…' : v} />
                <Tooltip
                  contentStyle={{ background: '#1a1a2e', border: '1px solid rgba(100,100,255,0.2)', borderRadius: 10, color: '#e8e8f0' }}
                  formatter={(val) => [`₹${val.toLocaleString()}`, 'Revenue']}
                />
                <Bar dataKey="revenue" fill="url(#suppGrad)" radius={[0, 6, 6, 0]} />
                <defs>
                  <linearGradient id="suppGrad" x1="0" y1="0" x2="1" y2="0">
                    <stop offset="0%" stopColor="#7c3aed" />
                    <stop offset="100%" stopColor="#00d4ff" />
                  </linearGradient>
                </defs>
              </BarChart>
            </ResponsiveContainer>
          </div>
        </div>

        {/* Products per Supplier */}
        <div className="card">
          <div className="card-title">Products Supplied</div>
          <div className="chart-container">
            <ResponsiveContainer width="100%" height="100%">
              <BarChart data={supplierChart}>
                <CartesianGrid strokeDasharray="3 3" stroke="rgba(255,255,255,0.05)" />
                <XAxis dataKey="name" tick={{ fill: '#9898b8', fontSize: 10 }} angle={-30} textAnchor="end" height={60} />
                <YAxis tick={{ fill: '#9898b8', fontSize: 11 }} />
                <Tooltip contentStyle={{ background: '#1a1a2e', border: '1px solid rgba(100,100,255,0.2)', borderRadius: 10, color: '#e8e8f0' }} />
                <Bar dataKey="products" fill="#10b981" radius={[6, 6, 0, 0]} />
              </BarChart>
            </ResponsiveContainer>
          </div>
        </div>
      </div>

      {/* Supplier Details Table */}
      <div className="card">
        <div className="card-title">Supplier Performance Scoreboard</div>
        <div className="table-wrapper">
          <table>
            <thead>
              <tr>
                <th>ID</th><th>Supplier</th><th>Email</th><th>Lead Time</th>
                <th>Reliability</th><th>Products</th><th>Categories</th>
                <th>Revenue Generated</th><th>Units Sold</th>
              </tr>
            </thead>
            <tbody>
              {performance.map((s, i) => (
                <tr key={s.supplier_id}>
                  <td style={{ color: 'var(--text-muted)', fontSize: 12 }}>{s.supplier_id}</td>
                  <td style={{ fontWeight: 600 }}>{s.name}</td>
                  <td style={{ fontSize: 12, color: 'var(--text-secondary)' }}>{s.contact_email || '—'}</td>
                  <td>
                    <span className={`badge ${s.lead_time_days <= 3 ? 'green' : s.lead_time_days <= 5 ? 'orange' : 'red'}`}>
                      {s.lead_time_days}d
                    </span>
                  </td>
                  <td>
                    <div style={{ display: 'flex', alignItems: 'center', gap: 6 }}>
                      <div style={{ width: 50, height: 5, background: 'rgba(255,255,255,0.1)', borderRadius: 3 }}>
                        <div style={{
                          width: `${s.reliability_score * 100}%`, height: '100%', borderRadius: 3,
                          background: s.reliability_score >= 0.9 ? '#10b981' : s.reliability_score >= 0.85 ? '#f59e0b' : '#ef4444'
                        }} />
                      </div>
                      <span style={{ fontSize: 12, fontWeight: 600 }}>{(s.reliability_score * 100).toFixed(0)}%</span>
                    </div>
                  </td>
                  <td style={{ fontWeight: 600 }}>{s.products_supplied}</td>
                  <td>{s.categories_covered}</td>
                  <td style={{ fontWeight: 600, color: 'var(--accent-green)' }}>
                    ₹{Math.round(s.total_revenue_generated).toLocaleString()}
                  </td>
                  <td>{s.total_units_sold?.toLocaleString()}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}
